    // ブロックのセル数（マス数）を計算
    getSize: function(shape) {
        let size = 0;
        for (let row = 0; row < shape.length; row++) {
            for (let col = 0; col < shape[row].length; col++) {
                if (shape[row][col]) {
                    size++;
                }
            }
        }
        return size;
    },

    // 指定されたサイズ範囲のブロック形状を取得
    filterBySize: function(minSize, maxSize) {
        const filtered = [];
        for (let i = 0; i < this.ALL.length; i++) {
            const size = this.getSize(this.ALL[i]);
            if (size >= minSize && size <= maxSize) {
                filtered.push(this.ALL[i]);
            }
        }
        return filtered;
    }
